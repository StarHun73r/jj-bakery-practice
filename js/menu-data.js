function F(name, color, children) {
  if (Array.isArray(color)) { children = color; color = null; }
  return { type: "folder", name: name, color: color, children: children };
}
function I(id, name, price, opts) {
  var item = { type: "item", id: id, name: name, price: price || 0 };
  for (var k in opts || {}) item[k] = opts[k];
  return item;
}

// P- (preorder) and W- (waste) buttons exist only on the register: they stay out of
// practice orders, Find it, Flashcards, the Sheet and Photos, and never get photos.
window.MENU_TREE.forEach(function (top) {
  if (!/^[PW]-/.test(top.name)) return;
  top.registerOnly = true;
  (function mark(nodes) {
    nodes.forEach(function (n) {
      if (n.type === "folder") mark(n.children);
      else { n.practice = false; n.registerOnly = true; }
    });
  })(top.children);
});
